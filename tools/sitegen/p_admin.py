def page_config(stats):
    b = []
    b.append('<p class="breadcrumb"><a href="index.html">ホーム</a> / <span>設定（SPRO）</span></p>')
    b.append('<h1>設定ルート：48 タスクの完全な索引</h1>')
    b.append('<p class="kicker">SPRO パス · 業務処理/カスタマイジング · 手順 · 実際の画面 —— すべて教材と一致</p>')
    b.append('<p>このページは「操作マニュアル式」の索引で、<b>SPRO の実際の順序</b>に従って A〜J の 10 グループに分けています。'
             '各タスクでは、教材原文のメニュー/IMG パス、T-code、手順の要点、そして実際のシステム画面を示します（元のファイル名は図に記載し、Word 原稿と照合できます）。'
             'パスのテキストは<b>クリックしてコピー</b>できます。</p>')
    b.append(toc([(g[0] + ". " + g[1], "grp" + g[0]) for g in CONFIG_GROUPS]
                 + [("K. 設定の順序がなぜこの順序なのか", "why"), ("L. セルフチェックリスト", "check")]))
    b.append(tbl(["グループ", "テーマ", "タスク番号", "タスク数"], [
        [g[0], g[1], "、".join("%02d" % n for n in g[3]), str(len(g[3]))] for g in CONFIG_GROUPS
    ]))

    for gid, gtitle, gkind, tasks, gdesc in CONFIG_GROUPS:
        b.append('<h2 id="grp%s">%s. %s</h2>' % (gid, gid, gtitle))
        b.append('<p>%s</p>' % gdesc)
        for n in tasks:
            t = TASK_JA[n]
            is_front = n in FRONT
            tags = [("fb", "業務処理" if is_front else "カスタマイジング（設定）")]
            for tc in stc(n):
                tags.append(("tc", tc))
            b.append('<div class="steph" id="task%02d"><span class="no">タスク %02d</span><h3>%s</h3>%s</div>'
                     % (n, n, esc(t["title"]),
                        "".join('<span class="%s">%s</span>' % (k, esc(v)) for k, v in tags)))
            b.append('<p>%s</p>' % NOTE1.get(n, ""))
            if spath(n):
                b.append(pathline("教材メニュー / IMG パス", spath(n)))
            if t["steps"]:
                items = step_items(n, t["steps"], TASK[n]["steps"])
                if items:
                    b.append('<p class="opcap"><span class="lead">手順の要点</span>（教材原文のステップごとの説明）</p>')
                    b.append(oplist(items, start=1))
            # 画面：最初のステップ + 最後のステップ（異なる場合）
            picks = []
            mk = lambda st, k=0: simg(n, st, k)

            def has(st):
                return bool(mk(st))

            p1 = mk(1)
            if p1:
                picks.append((p1, 1))
            last = len(t["steps"])
            if last > 1 and has(last):
                p2 = mk(last)
                if p2 and p2 != p1:
                    picks.append((p2, last))
            fig = []
            for i, (p, st) in enumerate(picks):
                cap = scap(n, st)
                if not cap.strip():
                    # そのステップに文字の説明がない（教材は「説明+スクリーンショット」型）→ このタスクの最初の非空の説明を使い、
                    # どれも空ならタスクのタイトルを使い、画面の内容をでっち上げない
                    caps = [s.get("caption", "").strip() for s in t["steps"]]
                    caps = [c for c in caps if c]
                    cap = caps[0] if caps else t["title"]
                if len(cap) > 90:
                    cap = cap[:88] + "…"
                fig.append((p, cap, "%02d-%d" % (n, i + 1)))
            if len(fig) == 1:
                b.append(shot(fig[0][0], no=fig[0][2], cap=fig[0][1], src=src_ref(n)))
            elif fig:
                b.append(shot_grid(fig))
        b.append('<hr class="sep">')

    b.append('<h2 id="why">K. 設定の順序がなぜこの順序なのか</h2>')
    b.append(steps_list([
        "<b>組織構造</b>（A〜C）：データも伝票も組織キーを入力する必要があり、組織が存在しないと後は何も登録できません。",
        "<b>得意先勘定グループと価格設定</b>（D〜F）：マスタの画面レイアウト、価格の計算方法、どの勘定に記帳するかは、いずれも「ルール」に属します。",
        "<b>パートナ決定</b>（G）：伝票上の役割がどこから来るのか。",
        "<b>マスタ</b>（H）：ルールを決めてから得意先と品目を登録します。マスタで入力するのは、まさにこれらのルール項目だからです。",
        "<b>伝票プロセス</b>（I）：設定とマスタがそろって初めて、受注伝票から請求書まで一気に流れます。",
        "<b>分析</b>（J）：最後に統計更新を有効にして、レポートにデータを出します。",
    ]))
    b.append(note("tip", "実習環境の現実",
                  "実際のプロジェクトでは、これらの設定の一部がすでに標準値（そのまま使用可能）である場合があり、すべてを自作する必要はありません。"
                  "コースの推奨：<b>まず A〜C と E を一通り実行する</b>（組織、出荷、価格設定）。残りは理解しておけばよく、必要になったらこのページを参照してください。"))

    b.append('<h2 id="check">L. セルフチェックリスト</h2>')
    b.append(box("ok", "設定が完了したら、この 5 項目で受け入れ確認",
                 "<ol><li>得意先マスタ：少なくとも 1 つの販売エリアで販売ビューを登録できる（VD01/XD01）。</li>"
                 "<li>品目マスタ：販売ビューを登録でき、明細カテゴリグループ、税分類、勘定割当グループに値があることが確認できる。</li>"
                 "<li>条件レコード：<code>VK13</code> で該当の販売エリア + 品目の PR00 価格を照会できます。</li>"
                 "<li>受注伝票：<code>VA01</code> で登録後に価格が自動で表示され、納入日の確定に値が入る。</li>"
                 "<li>全チェーン：受注伝票 → <code>VL01N</code> 納入 → 出庫過転記 → <code>VF01</code> 請求 → <code>VF02</code> リリース、"
                 "さらに <code>VF03</code> で会計伝票を確認できます。</li></ol>"))
    b.append(steps_list([
        '<a href="practice.html"><b>実習タスク</b></a> に戻り、5 つのタスクに沿って実習します。',
        '項目の意味が分からないときは <a href="glossary.html"><b>用語集</b></a> を参照。',
    ]))
    return b


